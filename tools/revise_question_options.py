def apply_revisions() -> tuple[int, int, dict[str, int]]:
    updated = 0
    found: set[str] = set()
    answer_position_cursor = 0
    position_counts = {letter: 0 for letter in "ABCD"}
    bank_dir = ROOT / "question_bank"
    paths = [bank_dir / "advanced_questions.json", *sorted(bank_dir.glob("curated_*.json"))]
    for path in paths:
        items = json.loads(path.read_text(encoding="utf-8"))
        changed = False
        for item in items:
            revision = REVISIONS.get(item["id"])
            if not revision:
                continue
            options = revision["options"]
            correct = revision["correct"]
            if len(options) != 4 or len(set(options)) != 4 or correct not in options:
                raise ValueError(f"Invalid revision for {item['id']}")
            item["options"] = options
            item["answer"] = correct
            item["answer_index"] = options.index(correct)
            found.add(item["id"])
            updated += 1
            changed = True
        for item in items:
            if item.get("type") != "single_choice":
                continue
            options = list(item.get("options", []))
            correct = item.get("answer")
            if len(options) != 4 or correct not in options:
                raise ValueError(f"Invalid single-choice question {item['id']}")
            options.remove(correct)
            target_index = answer_position_cursor % 4
            options.insert(target_index, correct)
            item["options"] = options
            item["answer_index"] = target_index
            position_counts["ABCD"[target_index]] += 1
            answer_position_cursor += 1
            changed = True
        if changed:
            path.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    missing = set(REVISIONS) - found
    if missing:
        raise KeyError(f"Question IDs not found: {sorted(missing)}")
    return updated, len(found), position_counts


if __name__ == "__main__":
    updated, found, positions = apply_revisions()
    print(f"UPDATED={updated} FOUND={found} POSITIONS={positions}")
